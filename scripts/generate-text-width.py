#!/usr/bin/env python3
"""Generate src/text-width.lisp from the pinned unicode-width crate."""
import argparse
import hashlib
import pathlib
import subprocess
import tempfile

ORACLE = r'''extern crate unicode_width;
use unicode_width::UnicodeWidthChar;
fn main() {
    let mut last: Option<usize> = None;
    let mut start = 0u32;
    for cp in 0..=0x10ffff {
        if (0xd800..=0xdfff).contains(&cp) { continue; }
        let c = char::from_u32(cp).unwrap();
        let width = c.width().unwrap_or(0);
        if Some(width) != last {
            if let Some(previous) = last {
                println!("{:X}..{:X} {}", start, cp - 1, previous);
            }
            start = cp;
            last = Some(width);
        }
    }
    println!("{:X}..{:X} {}", start, 0x10ffff, last.unwrap());
}'''

